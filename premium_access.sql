-- Notifications individuelles automatiques (demande créée, acceptée ou refusée)
create table if not exists public.stratx_user_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 160),
  body text not null check (char_length(body) between 1 and 1500),
  kind text not null default 'account' check (kind in ('account','premium_request','premium_approved','premium_rejected')),
  related_request_id bigint null references public.premium_payment_requests(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists stratx_user_notifications_user_created_idx on public.stratx_user_notifications(user_id, created_at desc);
alter table public.stratx_user_notifications enable row level security;
drop policy if exists "Users read own StratX notifications" on public.stratx_user_notifications;
create policy "Users read own StratX notifications" on public.stratx_user_notifications for select to authenticated using (auth.uid() = user_id);
grant select on public.stratx_user_notifications to authenticated;

create or replace function public.stratx_notify_premium_request_created()
returns trigger language plpgsql security definer set search_path = public, auth as $$
declare admin_user record;
begin
  for admin_user in select id from auth.users where raw_app_meta_data ->> 'role' = 'admin' loop
    insert into public.stratx_user_notifications(user_id,title,body,kind,related_request_id)
    values(admin_user.id,'Nouvelle demande Premium', 'Une nouvelle demande de ' || new.duration_days || ' jour(s) a été déposée. Vérifiez la transaction avant de valider.', 'premium_request',new.id);
  end loop;
  return new;
end; $$;
drop trigger if exists stratx_premium_request_created_notification on public.premium_payment_requests;
create trigger stratx_premium_request_created_notification after insert on public.premium_payment_requests
for each row when (new.status = 'pending') execute function public.stratx_notify_premium_request_created();

create or replace function public.stratx_notify_premium_request_decision()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if old.status = 'pending' and new.status in ('approved','rejected') then
    insert into public.stratx_user_notifications(user_id,title,body,kind,related_request_id)
    values(new.user_id,
      case when new.status='approved' then 'Demande Premium acceptée' else 'Demande Premium refusée' end,
      case when new.status='approved' then 'Votre paiement a été validé. Votre accès Premium est activé pour ' || new.duration_days || ' jour(s).' else 'Votre demande Premium a été refusée. Vérifiez la référence et contactez l’administrateur si vous pensez qu’il s’agit d’une erreur.' end,
      case when new.status='approved' then 'premium_approved' else 'premium_rejected' end,new.id);
  end if;
  return new;
end; $$;
drop trigger if exists stratx_premium_request_decision_notification on public.premium_payment_requests;
create trigger stratx_premium_request_decision_notification after update of status on public.premium_payment_requests
for each row execute function public.stratx_notify_premium_request_decision();

