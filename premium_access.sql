-- StratX Premium manual-payment validation workflow
-- Run in Supabase SQL Editor. Safe to re-run.
create table if not exists public.premium_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  status text not null default 'inactive' check (status in ('active', 'inactive', 'expired')),
  expires_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.premium_subscriptions enable row level security;
drop policy if exists "Users can read their own Premium status" on public.premium_subscriptions;
create policy "Users can read their own Premium status" on public.premium_subscriptions for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Admins manage Premium subscriptions" on public.premium_subscriptions;
create policy "Admins manage Premium subscriptions" on public.premium_subscriptions for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create table if not exists public.premium_payment_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  payment_method text not null check (payment_method in ('MVola','Orange Money','Airtel Money','Transfert bancaire / autre')),
  transaction_ref text not null,
  amount_ariary numeric(12,0) not null check (amount_ariary > 0),
  plan_code text not null default 'custom_30d',
  duration_days integer not null default 30 check (duration_days between 1 and 365),
  note text not null default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz null,
  reviewed_by uuid null references auth.users(id) on delete set null
);
create index if not exists premium_payment_requests_user_created_idx on public.premium_payment_requests(user_id, created_at desc);
alter table public.premium_payment_requests enable row level security;
drop policy if exists "Users submit own Premium requests" on public.premium_payment_requests;
create policy "Users submit own Premium requests" on public.premium_payment_requests for insert to authenticated with check (auth.uid() = user_id and status = 'pending');
drop policy if exists "Users read own Premium requests" on public.premium_payment_requests;
create policy "Users read own Premium requests" on public.premium_payment_requests for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Admins manage Premium requests" on public.premium_payment_requests;
create policy "Admins manage Premium requests" on public.premium_payment_requests for all to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
-- Admins must be assigned app_metadata.role = 'admin' by a trusted Supabase administrator.
-- Never set admin role from client-side code or user-editable user_metadata.

-- Migration idempotente pour les projets déjà installés.
alter table public.premium_payment_requests add column if not exists plan_code text not null default 'monthly';
alter table public.premium_payment_requests add column if not exists duration_days integer not null default 30;
alter table public.premium_payment_requests drop constraint if exists premium_payment_requests_duration_days_check;
alter table public.premium_payment_requests add constraint premium_payment_requests_duration_days_check check (duration_days between 1 and 365);
alter table public.premium_payment_requests drop constraint if exists premium_payment_requests_plan_code_check;
-- plan_code is intentionally flexible (e.g. custom_12d) for arbitrary durations.
update public.premium_payment_requests set plan_code = 'custom_' || duration_days::text || 'd' where plan_code is null or plan_code in ('weekly','monthly','quarterly');
grant select on public.premium_subscriptions to authenticated;
grant insert, select on public.premium_payment_requests to authenticated;
grant update, select on public.premium_payment_requests to authenticated;
grant usage, select on sequence public.premium_payment_requests_id_seq to authenticated;


-- Centre de notifications et annonces StratX
create table if not exists public.stratx_announcements (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 1500),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  published boolean not null default true
);
create index if not exists stratx_announcements_created_idx on public.stratx_announcements(created_at desc);
alter table public.stratx_announcements enable row level security;
drop policy if exists "Members read published announcements" on public.stratx_announcements;
create policy "Members read published announcements" on public.stratx_announcements for select to authenticated using (published = true);
drop policy if exists "Admins publish announcements" on public.stratx_announcements;
create policy "Admins publish announcements" on public.stratx_announcements for insert to authenticated with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin' and auth.uid() = created_by);
grant select on public.stratx_announcements to authenticated;
grant insert on public.stratx_announcements to authenticated;
grant usage, select on sequence public.stratx_announcements_id_seq to authenticated;
